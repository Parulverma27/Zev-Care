export function getPlanTheme(planName) {
  if (!planName) return PLAN_THEMES.Free;
  const normalized = String(planName).trim().toLowerCase();
  if (normalized.includes('free') || normalized.includes('none')) return PLAN_THEMES.Free;
  if (normalized.includes('platinum')) return PLAN_THEMES.Platinum;
  if (normalized.includes('gold')) return PLAN_THEMES.Gold;
  if (normalized.includes('silver')) return PLAN_THEMES.Silver;
  return PLAN_THEMES.Free;
}
