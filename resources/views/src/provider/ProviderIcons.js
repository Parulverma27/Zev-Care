/**
 * Usage: <ProviderIcon name="check" color="#fff" size={18} />
 */
export default function ProviderIcon({ name, color = '#0f172a', size = 18 }) {
  const iconFn = ICONS[name];
  if (!iconFn) return null;

  if (Platform.OS === 'web') {
    return (
      <span style={{ display: 'inline-flex', alignItems: 'center', justifyContent: 'center', flexShrink: 0 }}>
        {iconFn(color, size)}
      </span>
    );
  }

  // Native fallback — simple symbol text
  const fallbacks = {
    check: '✓', car: '→', pin: '•', flash: '⚡', clock: '◷',
    camera: '◉', key: '◈', star: '★', edit: '✎', logout: '→',
    back: '←', phone: '☎', mail: '✉', shield: '◆', send: '→',
    wallet: '₹', briefcase: '■', wrench: '⚙', user: '◉',
    checkCircle: '✓', arrowRight: '→',
  };
  return <Text style={{ color, fontSize: size * 0.7, lineHeight: size }}>{fallbacks[name] || '•'}</Text>;
}
